"""Export a perceptive Hiking checkpoint as a unitree_rl_lab ``g1_ctrl`` policy.

Writes ``<policy-dir>/exported/policy.onnx`` and ``<policy-dir>/params/``:

* ``deploy.yaml``      observations/actions/gains in unitree_rl_lab's format.
                       The waist sign conversion (policy = -Unitree) is folded
                       into negative observation and action scales.
* ``depth_camera.npz`` exact training ray directions, image-plane cosines and
                       the camera mount on Unitree's torso_link, for the
                       simulator's depth camera.
* ``deployment_contract.json`` the full interface description.

The policy needs the ``hiking_*`` observation terms added to unitree_rl_lab
(``deploy/include/isaaclab/envs/mdp/observations/hiking_observations.h``):
torso-frame IMU computed from the pelvis IMU and waist encoders, and a
37-frame depth ring read from the ``rt/hiking/depth`` PointCloud2 topic.

    python scripts/export_unitree_rl_lab.py --checkpoint policy.pt \\
        --policy-dir ../unitree_rl_lab/deploy/robots/g1_29dof/config/policy/hiking/<name>
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OBSERVATION_INPUT = "obs"   # unitree_rl_lab's single observation group name


def _flow(values, digits=6):
    return "[" + ", ".join(f"{float(v):.{digits}g}" for v in values) + "]"


def deploy_yaml(contract: dict, checkpoint: str) -> str:
    import numpy as np
    joints = contract["joints"]
    sign = np.asarray(joints["unitree_sign"], float)
    default_policy = np.asarray(joints["default_position_policy"], float)
    scale = np.asarray(joints["action_scale"], float)
    names = joints["order"]
    waist = [i for i, s in enumerate(sign) if s < 0]
    lines = [
        f"# Generated by G1_Perceptive_WMAC/scripts/export_unitree_rl_lab.py from {checkpoint}",
        "# Joint order is the Unitree SDK order: " + ", ".join(names),
        "# Hiking's torso-rooted URDF reverses the waist: policy angle = -Unitree angle for joints "
        f"{waist}. Negative entries in the joint observation/action scales perform that conversion.",
        f"joint_ids_map: {list(range(len(names)))}",
        f"step_dt: {contract['timing']['control_dt_s']}",
        f"stiffness: {_flow(joints['kp'])}",
        f"damping: {_flow(joints['kd'])}",
        "# Unitree convention (waist defaults are zero, so identical to the policy convention).",
        f"default_joint_pos: {_flow(sign * default_policy)}",
        "commands:",
        "  base_velocity:",
        "    ranges:  # training: vx 0 (standing) or 0.45-1.0 m/s, vy 0, yaw rate -1..1 rad/s",
        "      lin_vel_x: [0.0, 1.0]",
        "      lin_vel_y: [0.0, 0.0]",
        "      ang_vel_z: [-1.0, 1.0]",
        "      heading: null",
        "actions:",
        "  JointPositionAction:",
        "    clip: null",
        "    joint_names: [.*]",
        "    # Unitree target = sign * (default + action_scale * action)",
        f"    scale: {_flow(sign * scale)}",
        f"    offset: {_flow(sign * default_policy)}",
        "    joint_ids: null",
        "observations:  # order and widths must match the ONNX input; each term holds 8 samples, oldest first",
        "  hiking_torso_ang_vel:  # torso_link frame, from pelvis IMU + waist encoders",
        "    params: {waist_joint_ids: [12, 13, 14]}",
        "    clip: null",
        "    scale: [0.25, 0.25, 0.25]",
        "    history_length: 8",
        "  hiking_torso_projected_gravity:",
        "    params: {waist_joint_ids: [12, 13, 14]}",
        "    clip: null",
        "    scale: [1.0, 1.0, 1.0]",
        "    history_length: 8",
        "  velocity_commands:",
        "    params: {command_name: base_velocity}",
        "    clip: null",
        "    scale: [1.0, 1.0, 1.0]",
        "    history_length: 8",
        "  joint_pos_rel:  # (q - default) in the policy convention",
        "    params: {}",
        "    clip: null",
        f"    scale: {_flow(sign)}",
        "    history_length: 8",
        "  joint_vel_rel:",
        "    params: {}",
        "    clip: null",
        f"    scale: {_flow(0.05 * sign)}",
        "    history_length: 8",
        "  last_action:",
        "    params: {}",
        "    clip: null",
        f"    scale: {_flow(np.ones(len(names)))}",
        "    history_length: 8",
        "  hiking_depth_ring:  # 37 frames x [depth/2.5, valid] x 36 x 64; crop/blur/clip happen inside the ONNX",
        "    params: {topic: rt/hiking/depth, ring_length: 37, height: 36, width: 64, max_depth: 2.5}",
        "    clip: null",
        "    scale: null",
        "    history_length: 1",
    ]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--policy-dir", type=Path, required=True)
    args = parser.parse_args(argv)
    import numpy as np
    import torch
    from scripts.evaluate_wmac_perceptive import load_actor
    from src.tasks.amp_perceptive.sensors import HikingDepthPatternCfg
    from src.wmac_perceptive.onnx_export import export_raw_packed_actor
    from src.wmac_perceptive.unitree_interface import deployment_contract

    checkpoint = args.checkpoint.expanduser().resolve()
    actor, cfg, payload = load_actor(checkpoint, "cpu")
    if cfg.hiking_training_version < 3:
        parser.error("Only Hiking v3 checkpoints are supported")
    exported, params = args.policy_dir / "exported", args.policy_dir / "params"
    exported.mkdir(parents=True, exist_ok=True)
    params.mkdir(parents=True, exist_ok=True)
    onnx_path = exported / "policy.onnx"
    export_raw_packed_actor(actor, onnx_path, input_name=OBSERVATION_INPUT, dynamic_batch=False)
    camera = payload["architecture"]["camera"]
    contract = deployment_contract(camera=camera, checkpoint=str(checkpoint))
    contract["onnx_input"]["name"] = OBSERVATION_INPUT
    (params / "deployment_contract.json").write_text(json.dumps(contract, indent=1) + "\n")
    (params / "deploy.yaml").write_text(deploy_yaml(contract, checkpoint.name))
    pattern = HikingDepthPatternCfg(sensor_protocol=cfg.sensor_protocol)
    directions, cosines = pattern.optical_rays("cpu")
    mount = contract["depth"]["camera_mount_unitree_torso_link"]
    np.savez(params / "depth_camera.npz",
             directions_camera=directions.double().numpy(), image_plane_cosine=cosines.double().numpy(),
             width=pattern.width, height=pattern.height,
             mount_position_unitree_torso=np.asarray(mount["position"]),
             mount_quat_wxyz=np.asarray(mount["rotation_wxyz"]),
             min_ray_distance=0.1, max_depth=2.5, camera_body="torso_link",
             convention="camera x forward, y left, z up; rays rotated by mount_quat into torso_link")
    # Cross-check the fixed-batch ONNX against the PyTorch Actor.
    import onnxruntime
    sample = torch.zeros(1, actor.spec.packed_dim)
    sample[:, :actor.spec.proprio_dim].normal_()
    sample[:, actor.spec.proprio_dim:] = torch.rand(1, actor.spec.packed_dim - actor.spec.proprio_dim)
    with torch.inference_mode():
        expected = actor(sample).numpy()
    session = onnxruntime.InferenceSession(str(onnx_path), providers=["CPUExecutionProvider"])
    shape = session.get_inputs()[0].shape
    got = session.run(None, {OBSERVATION_INPUT: sample.numpy()})[0]
    error = float(np.abs(got - expected).max())
    print(f"Wrote {args.policy_dir}: ONNX input {OBSERVATION_INPUT}{shape}, max |ONNX - PyTorch| {error:.2e}")
    if error > 1e-4 or any(not isinstance(d, int) for d in shape):
        raise SystemExit("ONNX export check failed")


if __name__ == "__main__":
    main()
